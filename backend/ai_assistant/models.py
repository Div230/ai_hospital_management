from django.db import models
from core.models import BaseModel


class SymptomCheckSession(BaseModel):
    """One multi-turn AI Symptom Checker conversation, driven by LangGraph."""
    STATUS_CHOICES = (('ACTIVE', 'Active'), ('COMPLETED', 'Completed'))

    patient = models.ForeignKey('patients.Patient', on_delete=models.CASCADE, related_name='symptom_sessions')
    status = models.CharField(max_length=15, choices=STATUS_CHOICES, default='ACTIVE')
    initial_complaint = models.TextField()
    conversation_history = models.JSONField(default=list, blank=True, help_text='list of {role, content}')
    possible_conditions = models.JSONField(default=list, blank=True)
    risk_level = models.CharField(max_length=20, blank=True, help_text='LOW / MODERATE / HIGH / EMERGENCY')
    recommendation = models.TextField(blank=True)

    def __str__(self):
        return f'SymptomCheck: {self.patient} - {self.initial_complaint[:40]}'


class AIHealthAssistantMessage(BaseModel):
    """General-purpose free-form AI health assistant chat log (separate from structured symptom checker)."""
    ROLE_CHOICES = (('user', 'User'), ('assistant', 'Assistant'))
    patient = models.ForeignKey('patients.Patient', on_delete=models.CASCADE, related_name='ai_chat_messages')
    role = models.CharField(max_length=10, choices=ROLE_CHOICES)
    content = models.TextField()

    class Meta:
        ordering = ['created_at']


class DiseaseRiskPrediction(BaseModel):
    patient = models.ForeignKey('patients.Patient', on_delete=models.CASCADE, related_name='risk_predictions')
    condition_name = models.CharField(max_length=150)
    risk_percentage = models.DecimalField(max_digits=5, decimal_places=2)
    contributing_factors = models.JSONField(default=list, blank=True)
    recommendation = models.TextField(blank=True)
    based_on_report = models.ForeignKey(
        'patients.MedicalReport', on_delete=models.SET_NULL, null=True, blank=True, related_name='+',
    )


class AIRecommendation(BaseModel):
    """Diet / Exercise / Lifestyle suggestions generated by the AI layer."""
    CATEGORY_CHOICES = (('DIET', 'Diet'), ('EXERCISE', 'Exercise'), ('LIFESTYLE', 'Lifestyle'))
    patient = models.ForeignKey('patients.Patient', on_delete=models.CASCADE, related_name='ai_recommendations')
    category = models.CharField(max_length=15, choices=CATEGORY_CHOICES)
    content = models.JSONField(default=dict, help_text='structured recommendation items')
    generated_reason = models.TextField(blank=True)
